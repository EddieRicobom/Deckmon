/**
 * Effect coverage report. Parses every card in DigimonCards.json and reports, per set and overall, how many cards are
 * fully parsed (every line parsed, static or overridden), partially parsed, or unparsed, plus the most common
 * unparsed line templates. Set EFFECT_COVERAGE_WRITE=1 to write core/effects/COVERAGE.md.
 */
import * as fs from 'fs';
import * as path from 'path';
import { parsedCard } from './parser';

interface RawCard {
  id?: string;
  cardType?: string;
  effect?: string;
  digivolveEffect?: string;
  securityEffect?: string;
}

const DATA = path.resolve(__dirname, '../../../../../assets/cardlists/DigimonCards.json');
const REPORT = path.resolve(__dirname, 'COVERAGE.md');
const TOP_N = 50;

const clean = (v: unknown): string => (typeof v === 'string' && v !== '-' ? v : '');

/** Normalises an unparsed line to a template: numbers become N, bracketed names become [X], keywords become <K>. */
export function template(line: string): string {
  return line
    .replace(/＜[^＞]+＞/g, (k) => `＜${/^＜([A-Za-z-]+)/.exec(k)?.[1] ?? 'K'}＞`)
    .replace(/\[[^\]]+\]/g, '[X]')
    .replace(/[+-]?\d+/g, 'N')
    .replace(/\s+/g, ' ')
    .trim();
}

interface Tally {
  total: number;
  full: number;
  override: number;
  partial: number;
  unparsed: number;
}

const emptyTally = (): Tally => ({ total: 0, full: 0, override: 0, partial: 0, unparsed: 0 });

function pct(n: number, d: number): string {
  return d === 0 ? '-' : `${((100 * n) / d).toFixed(1)}%`;
}

describe('effect coverage', () => {
  it('parses every card and reports coverage', () => {
    const cards = JSON.parse(fs.readFileSync(DATA, 'utf8')) as RawCard[];
    const perSet = new Map<string, Tally>();
    const overall = emptyTally();
    const st = emptyTally();
    const templates = new Map<string, number>();
    const seen = new Set<string>();
    const dump: string[] = [];

    for (const card of cards) {
      const id = String(card.id ?? '');
      if (!id || seen.has(id)) continue;
      seen.add(id);
      const set = /^([A-Za-z]+\d*)-/.exec(id)?.[1] ?? id.split('-')[0];
      const texts = { effect: clean(card.effect), digivolveEffect: clean(card.digivolveEffect), securityEffect: clean(card.securityEffect) };
      const parsed = parsedCard(id, texts);
      const lines = parsed.lines.filter((l) => l.text.length > 0);
      const unparsed = lines.filter((l) => l.status === 'unparsed');
      const kind: keyof Omit<Tally, 'total'> = parsed.override
        ? 'override'
        : unparsed.length === 0
          ? 'full'
          : lines.length > unparsed.length
            ? 'partial'
            : 'unparsed';
      if (!perSet.has(set)) perSet.set(set, emptyTally());
      const setTally = perSet.get(set)!;
      for (const bucket of [overall, setTally, ...(/^ST([1-9]|10)$/.test(set) ? [st] : [])]) {
        bucket.total++;
        bucket[kind]++;
      }
      for (const l of unparsed) templates.set(template(l.text), (templates.get(template(l.text)) ?? 0) + 1);
      if (/^ST([1-9]|10)$/.test(set)) for (const l of unparsed) dump.push(`${id} ${l.field} | ${l.text}`);
    }

    const sets = [...perSet.keys()].sort();
    const rows = sets.map((s) => {
      const t = perSet.get(s)!;
      return `| ${s} | ${t.total} | ${pct(t.full + t.override, t.total)} | ${pct(t.partial, t.total)} | ${pct(t.unparsed, t.total)} |`;
    });
    const top = [...templates.entries()].sort((a, b) => b[1] - a[1]).slice(0, TOP_N);
    const topRows = top.map(([t, n], i) => `${i + 1}. (${n}) \`${t}\``);
    const stDone = st.full + st.override;

    const md = [
      '# Effect coverage',
      '',
      'Generated by `core/effects/coverage.spec.ts` from `src/assets/cardlists/DigimonCards.json`.',
      'Regenerate with `EFFECT_COVERAGE_WRITE=1 npx jest src/app/features/play/core/effects/coverage.spec.ts`.',
      '',
      'Fully = every text line parsed or a recognised static keyword. Overridden = hand-written in overrides.ts.',
      'Partial = some lines parsed. Unparsed = no line parsed. Unparsed lines keep their reminder.',
      '',
      `## Overall`,
      '',
      `- Cards: ${overall.total}`,
      `- Fully parsed: ${overall.full} (${pct(overall.full, overall.total)})`,
      `- Overridden: ${overall.override} (${pct(overall.override, overall.total)})`,
      `- Partially parsed: ${overall.partial} (${pct(overall.partial, overall.total)})`,
      `- Unparsed: ${overall.unparsed} (${pct(overall.unparsed, overall.total)})`,
      '',
      `## ST1-ST10 target (>= 90% fully parsed)`,
      '',
      `- Cards: ${st.total}`,
      `- Fully parsed or overridden: ${stDone} (${pct(stDone, st.total)})`,
      `- Partially parsed: ${st.partial}, unparsed: ${st.unparsed}`,
      '',
      '## Per set',
      '',
      '| Set | Cards | Full (incl. overrides) | Partial | Unparsed |',
      '| --- | ---: | ---: | ---: | ---: |',
      ...rows,
      '',
      `## Top ${TOP_N} unparsed line templates`,
      '',
      ...topRows,
      '',
    ].join('\n');

    if (process.env['EFFECT_COVERAGE_WRITE'] === '1') fs.writeFileSync(REPORT, md, 'utf8');
    if (process.env['EFFECT_COVERAGE_DUMP']) fs.writeFileSync(process.env['EFFECT_COVERAGE_DUMP'], dump.join('\n'), 'utf8');
    // eslint-disable-next-line no-console
    console.log(`ST1-10: ${stDone}/${st.total} full (${pct(stDone, st.total)}); overall ${overall.full}/${overall.total} full`);
    expect(overall.total).toBeGreaterThan(0);
  });
});
